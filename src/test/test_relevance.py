def top_ids(word: str, n: int = 4) -> list[str]:
    return [STRONG_IDS[i] for i, _ in STRONG_MATCHER.get_matches(word, n)]


def top_four_rate(words: dict[str, list[str]]) -> float:
    hits = [
        word for word, expected in words.items() if set(expected) & set(top_ids(word))
    ]
    return len(hits) / len(words)


@pytest.mark.model
def test_held_out_words_usually_reach_the_top_four():
    assert top_four_rate(HELD_OUT) >= 0.8


# Each floor sits just below the current rate, so these catch regressions rather than set targets.
@pytest.mark.model
@pytest.mark.parametrize(
    "category, floor",
    [
        ("rare", 0.95),
        ("inflected", 0.75),
        ("phrase", 0.85),
        ("synonym", 0.8),
        ("function", 0.8),
        ("aramaic", 0.85),
        ("name", 0.9),
        ("archaic", 0.65),
    ],
)
def test_each_kind_of_word_usually_reaches_the_top_four(category, floor):
    assert top_four_rate(DIVERSE[category]) >= floor


@pytest.mark.model
@pytest.mark.parametrize(
    "word, expected",
    [
        ("see", "H7200"),
        ("name", "H8034"),
        ("go", "H1980"),
        ("great", "H1419"),
        ("heaven", "H8064"),
        ("walking", "H1980"),
        ("kings", "H4428"),
    ],
)
def test_common_words_find_their_usual_hebrew_word(word, expected):
    assert expected in top_ids(word)
